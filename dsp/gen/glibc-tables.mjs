// converts the tables of glibc's pow (e_pow_log_data.c, e_exp_data.c) into Rust arrays of bits
import { readFileSync } from 'node:fs';
const [dir] = process.argv.slice(2);
const hexBits = (text) => {
  const m = /^(-?)0x([01])(?:\.([0-9a-fA-F]*))?p([+-]?\d+)$/.exec(text.trim());
  if (!m) throw new Error(`not a hex float: ${text}`);
  const [, sign, lead, frac = '', exp] = m;
  if (lead === '0') {
    if (/^0*$/.test(frac)) return sign ? 0x8000000000000000n : 0n;
    throw new Error('subnormal');
  }
  if (frac.length > 13) throw new Error('long fraction');
  const mant = BigInt('0x' + (frac + '0'.repeat(13 - frac.length)));
  const e = BigInt(Number(exp) + 1023);
  return (sign ? 1n << 63n : 0n) | (e << 52n) | mant;
};
// a hex float times a power of two (the scaled coefficients)
const scaled = (text) => {
  const [value, factor] = text.split('*').map((s) => s.trim());
  let bits = hexBits(value);
  if (factor) {
    const f = Number(factor);
    const k = Math.log2(Math.abs(f));
    if (!Number.isInteger(k)) throw new Error('not a power of two');
    bits += BigInt(k) << 52n;
    if (f < 0) bits ^= 1n << 63n;
  }
  return bits;
};
const hex = (bits) => `0x${bits.toString(16).padStart(16, '0')}`;
const pow = readFileSync(`${dir}/e_pow_log_data.c`, 'utf8');
const exp = readFileSync(`${dir}/e_exp_data.c`, 'utf8');
const field = (src, name) => scaled(new RegExp(`\\.${name} = ([^,]+),`).exec(src)[1]);
const block = (src, name) => new RegExp(`\\.${name} = \\{([\\s\\S]*?)\\n\\}`).exec(src)[1];
const values = (text) =>
  text
    .split('\n')
    .map((l) => l.replace(/\/\/.*$/, '').trim())
    .filter((l) => l && !l.startsWith('#'))
    .flatMap((l) =>
      l
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
    );
const out = [];
out.push(
  '// generated by dsp/gen/glibc-tables.mjs from glibc (sysdeps/ieee754/dbl-64/e_pow_log_data.c, e_exp_data.c)'
);
out.push('// the tables of pow, as bits\n');
out.push(`pub const POW_LN2HI: u64 = ${hex(field(pow, 'ln2hi'))};`);
out.push(`pub const POW_LN2LO: u64 = ${hex(field(pow, 'ln2lo'))};`);
const poly = values(block(pow, 'poly')).map(scaled);
out.push(`pub const POW_POLY: [u64; ${poly.length}] = [${poly.map(hex).join(', ')}];`);
const rows = [...block(pow, 'tab').matchAll(/^A\((-?0x[^,]+),([^,]+),([^)]+)\)/gm)].map((m) =>
  m.slice(1).map(scaled)
);
out.push(`// invc, logc, logctail\npub const POW_TAB: [[u64; 3]; ${rows.length}] = [`);
rows.forEach((r) => out.push(`    [${r.map(hex).join(', ')}],`));
out.push('];');
out.push(
  `pub const EXP_INVLN2N: u64 = ${hex(scaled(/\.invln2N = ([^,]+),/.exec(exp)[1].replace('N', '128')))};`
);
out.push(`pub const EXP_NEGLN2HIN: u64 = ${hex(field(exp, 'negln2hiN'))};`);
out.push(`pub const EXP_NEGLN2LON: u64 = ${hex(field(exp, 'negln2loN'))};`);
out.push(`pub const EXP_SHIFT: u64 = ${hex(field(exp, 'shift'))};`);
const epoly = values(block(exp, 'poly')).map(scaled);
out.push(`pub const EXP_POLY: [u64; ${epoly.length}] = [${epoly.map(hex).join(', ')}];`);
const tab = values(block(exp, 'tab')).map((v) => BigInt(v));
out.push(`pub const EXP_TAB: [u64; ${tab.length}] = [`);
for (let i = 0; i < tab.length; i += 2) out.push(`    ${hex(tab[i])}, ${hex(tab[i + 1])},`);
out.push('];');
console.log(out.join('\n'));
