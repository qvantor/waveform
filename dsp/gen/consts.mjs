// writes dsp/dsp-core/src/consts.rs: the tables the TS cores work out when their modules load (consts-entry.ts),
// computed by that TS code under jsmath, as the bits of each double. `--check` writes nothing and fails when the
// file differs (CI): a change of the TS tables must be carried over to the Rust cores
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';
import { installJsMath } from './jsmath.mjs';

const OUT = 'dsp/dsp-core/src/consts.rs';
const check = process.argv.includes('--check');

installJsMath();
const { outputFiles } = await build({
  entryPoints: ['dsp/gen/consts-entry.ts'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  write: false,
  define: { __PERF__: 'false' },
  // x ** y as Math.pow(x, y): jsmath's
  supported: { 'exponent-operator': false },
  logLevel: 'warning',
});
const ts = await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);

const view = new DataView(new ArrayBuffer(8));
const bits = (value) => {
  view.setFloat64(0, value);
  return `f64::from_bits(0x${view.getBigUint64(0).toString(16).padStart(16, '0')})`;
};
const scalar = (name, value, comment) => `// ${comment}\npub const ${name}: f64 = ${bits(value)};\n`;
const table = (name, rows, comment) => {
  const width = rows[0].length;
  const body = rows.map((row) => `    [\n${[...row].map((v) => `        ${bits(v)},`).join('\n')}\n    ],`);
  return `// ${comment}\npub const ${name}: [[f64; ${width}]; ${rows.length}] = [\n${body.join('\n')}\n];\n`;
};

const source = [
  '// generated by dsp/gen/consts.mjs from the TS cores (dsp/gen/consts-entry.ts): do not edit, run `node dsp/gen/consts.mjs`',
  '',
  '#![allow(clippy::unreadable_literal)]',
  '',
  scalar('CEILING', ts.CEILING, 'limiter-dsp.ts: the ceiling of the limiter, 10 ** (CEILING_DB / 20)'),
  scalar(
    'TRUE_PEAK_BOUND',
    ts.TRUE_PEAK_BOUND,
    'true-peak.ts: the sum of the absolute taps of the half sample phase'
  ),
  table(
    'TRUE_PEAK_PHASES',
    ts.TRUE_PEAK_PHASES,
    'true-peak.ts: the phases 1..3 of the 4× interpolator, cut at the nyquist'
  ),
  table('UP_PHASES', ts.UP_PHASES, 'oversampler.ts: the phases 0..3 of up(), cut at 0.9 × the nyquist'),
  table('DOWN_PHASES', ts.DOWN_PHASES, 'oversampler.ts: the phases 1..3 of down(), cut at the nyquist'),
  table(
    'MAKEUP_TABLES',
    ts.MAKEUP_TABLES,
    'distortion-makeup.ts: the makeup gain (dB) of each mode from 0 dB of drive up, every 0.25 dB'
  ),
].join('\n');

if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing: differs
  }
  if (current !== source) {
    console.error(`${OUT} differs from the tables of the TS cores: run \`node dsp/gen/consts.mjs\``);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, source);
  console.log(`wrote ${OUT}`);
}
